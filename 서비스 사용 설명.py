steps = [
    (
        "1단계: 카메라 열기",
        "메뉴에서 '카메라 인식 시스템' 페이지로 이동합니다.",
    ),
    (
        "2단계: 버스 촬영하기",
        "버스의 앞면이나 옆면에 표시된 노선 번호가 잘 보이도록 촬영합니다.",
    ),
    (
        "3단계: 번호 인식하기",
        "'버스 번호 인식하기' 버튼을 눌러 사진 분석을 시작합니다.",
    ),
    (
        "4단계: 안내 확인하기",
        "인식 결과를 확인하고 음성 안내 기능으로 번호를 다시 들을 수 있습니다.",
    ),
    (
        "5단계: 다시 촬영하기",
        "번호를 확인하지 못했다면 카메라 방향이나 거리를 조절해 다시 촬영합니다.",
    ),
]

